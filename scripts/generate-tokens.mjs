import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, URL } from "node:url";
import process from "node:process";
import { colors } from "../src/styles/tokens.mjs";

const declarations = (mode) =>
  Object.entries(colors)
    .flatMap(([name, values]) => {
      assert(/^[a-z-]+\/[a-z-]+$/.test(name));
      const hex = values[mode];
      assert(/^#[0-9A-F]{6}$/.test(hex), `Invalid ${mode} token ${name}`);
      const rgb = [1, 3, 5].map((index) => parseInt(hex.slice(index, index + 2), 16)).join(" ");
      const variable = name.replaceAll("/", "-");
      return [`  --${variable}: ${hex};`, `  --${variable}-rgb: ${rgb};`];
    })
    .join("\n");
const light = declarations("light");
const dark = declarations("dark");
const css = `/* Generated by scripts/generate-tokens.mjs from src/styles/tokens.mjs. */
:root,
[data-theme="light"] {
  color-scheme: light;
${light}
}

[data-theme="dark"] {
  color-scheme: dark;
${dark}
}

/* Initial paint before the theme controller runs; explicit overrides win. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme]) {
    color-scheme: dark;
${dark
  .split("\n")
  .map((line) => `  ${line}`)
  .join("\n")}
  }
}
`;
const paths = ["src/styles/tokens.css", "docs/assets/tokens.css"];
for (const path of paths) {
  const full = fileURLToPath(new URL(`../${path}`, import.meta.url));
  if (process.argv.includes("--check")) {
    assert.equal((await readFile(full, "utf8")).replace(/\r\n/g, "\n"), css, `Regenerate ${path}`);
  } else await writeFile(full, css);
}
globalThis.console.log(
  `${process.argv.includes("--check") ? "Verified" : "Generated"} ${Object.keys(colors).length} light/dark tokens for app and site.`,
);
