import { writeFile } from "node:fs/promises";
import { fileURLToPath, URL } from "node:url";

// Analytic unit-mass damped spring, sampled into CSS linear() stops. No runtime JS.
export function springStops(stiffness, damping, durationMs, samples = 40) {
  const decay = damping / 2;
  const frequency = Math.sqrt(stiffness - decay * decay);
  const position = (time) =>
    1 -
    Math.exp(-decay * time) *
      (Math.cos(frequency * time) + (decay / frequency) * Math.sin(frequency * time));
  const end = position(durationMs / 1000);
  return Array.from({ length: samples + 1 }, (_, index) => {
    const value = index === samples ? 1 : position((durationMs * index) / samples / 1000) / end;
    return `${Number(value.toFixed(5))} ${(index * 100) / samples}%`;
  }).join(", ");
}

export async function generateIslandMotion() {
  const curves = [
    ["live", 380, 32, 260],
    ["peek", 300, 28, 320],
    ["expanded", 260, 30, 380],
  ];
  const declarations = curves
    .map(
      ([name, stiffness, damping, ms]) =>
        `  --spring-${name}: linear(${springStops(stiffness, damping, ms)});`,
    )
    .join("\n");
  await writeFile(
    fileURLToPath(new URL("../spikes/island/motion.css", import.meta.url)),
    `/* Generated by scripts/generate-island-motion.mjs; do not edit. */\n:root {\n${declarations}\n}\n`,
  );
}
