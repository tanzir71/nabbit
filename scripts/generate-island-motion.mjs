import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import { fileURLToPath, URL } from "node:url";

// Analytic unit-mass damped spring, sampled into CSS linear() stops. No runtime JS.
export function springStops(stiffness, damping, durationMs, samples = 40) {
  const decay = damping / 2;
  const frequency = Math.sqrt(stiffness - decay * decay);
  const position = (time) =>
    1 -
    Math.exp(-decay * time) *
      (Math.cos(frequency * time) + (decay / frequency) * Math.sin(frequency * time));
  const end = position(durationMs / 1000);
  return Array.from({ length: samples + 1 }, (_, index) => {
    const value = index === samples ? 1 : position((durationMs * index) / samples / 1000) / end;
    return `${Number(value.toFixed(5))} ${(index * 100) / samples}%`;
  }).join(", ");
}

export async function generateIslandMotion() {
  const curves = [
    ["live", 380, 32, 260],
    ["peek", 300, 28, 320],
    ["expanded", 260, 30, 380],
  ];
  const declarations = curves
    .map(
      ([name, stiffness, damping, ms]) =>
        `  --spring-${name}: linear(${springStops(stiffness, damping, ms)});`,
    )
    .join("\n");
  const css = `/* Generated by scripts/generate-island-motion.mjs; do not edit. */\n:root {\n${declarations}\n}\n`;
  for (const path of ["../src/styles/island-motion.css", "../spikes/island/motion.css"]) {
    const target = new URL(path, import.meta.url);
    const existing = await readFile(target, "utf8").catch((error) => {
      if (error.code === "ENOENT") return null;
      throw error;
    });
    // Preserve identical generated files while native compilers have them open.
    if (existing !== css) await writeFile(target, css);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1])
  await generateIslandMotion();
